//! Durable, secret-free identity fences for temporary secret references.
//!
//! These checks run inside the caller's reference transaction. They never acquire
//! the store mutex again, refresh an authentication proof, or evaluate grants.
use super::*;
use subtle::ConstantTimeEq;

impl BrokerTokenHasher {
    /// A private, domain-separated binding to the loaded verifier key. It lets
    /// a retained origin notice key rotation without retaining a bearer token.
    pub(crate) fn secret_reference_key_binding(&self) -> [u8; 32] {
        let mut mac = <HmacSha256 as Mac>::new_from_slice(self.key.as_ref())
            .expect("HMAC accepts a 32-byte key");
        mac.update(b"agent-access/temporary-secret-origin/token-verifier/v1");
        mac.finalize().into_bytes().into()
    }
}

/// Only immutable row identities and monotonic versions leave the live proof.
/// The attested username and identity-token fingerprint are deliberately absent.
#[derive(Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub(crate) struct AttestedSecretReferencePin {
    pub(super) principal: String,
    pub(super) gate_incarnation: String,
    pub(super) gate_version: i64,
    pub(super) binding: AttestedSecretReferenceBinding,
}

#[derive(Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub(super) enum AttestedSecretReferenceBinding {
    Username {
        binding_id: String,
        binding_version: i64,
    },
    Fingerprint {
        inventory_revision: i64,
    },
}

impl AttestedSecretReferencePin {
    pub(crate) fn valid_shape(&self) -> bool {
        is_safe_principal(&self.principal)
            // Human gates are generated by SQLite lower(hex(randomblob(16))).
            // Username binding IDs below use the separate UUID encoding.
            && self.gate_incarnation.len() == 32
            && self.gate_incarnation.bytes().all(|byte| {
                byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte)
            })
            && self.gate_version > 0
            && match &self.binding {
                AttestedSecretReferenceBinding::Username {
                    binding_id,
                    binding_version,
                } => {
                    validate_canonical_uuid(binding_id, "identity binding").is_ok()
                        && *binding_version > 0
                }
                AttestedSecretReferenceBinding::Fingerprint { inventory_revision } => {
                    *inventory_revision > 0
                }
            }
    }

    pub(crate) fn principal(&self) -> &str {
        &self.principal
    }

    pub(crate) fn authentication_kind(&self) -> &'static str {
        match self.binding {
            AttestedSecretReferenceBinding::Username { .. } => "trusted_user",
            AttestedSecretReferenceBinding::Fingerprint { .. } => "forwarded_identity",
        }
    }

    pub(crate) fn check_current_conn(&self, conn: &Connection) -> Result<(), ManagedStoreError> {
        let principal = principal_by_id_without_groups(conn, &self.principal)?;
        if principal.kind != "user" || principal.status != "active" {
            return Err(ManagedStoreError::AttestedIdentityDenied);
        }
        let gate = identity_access::identity_access_conn(conn, &self.principal)?;
        if gate.paused
            || gate.incarnation != self.gate_incarnation
            || gate.version != self.gate_version
        {
            return Err(ManagedStoreError::AttestedIdentityDenied);
        }
        let current = match &self.binding {
            AttestedSecretReferenceBinding::Username {
                binding_id,
                binding_version,
            } => conn.query_row(
                "SELECT EXISTS(SELECT 1 FROM principal_username_bindings
                 WHERE binding_id=?1 AND principal_id=?2 AND version=?3 AND enabled=1)",
                params![binding_id, self.principal, binding_version],
                |row| row.get::<_, bool>(0),
            ),
            AttestedSecretReferenceBinding::Fingerprint { inventory_revision } => conn.query_row(
                "SELECT EXISTS(SELECT 1 FROM principal_identity_tokens
                 WHERE principal_id=?1 AND revision=?2 AND fingerprint IS NOT NULL)",
                params![self.principal, inventory_revision],
                |row| row.get::<_, bool>(0),
            ),
        }
        .map_err(sql_unavailable)?;
        if !current {
            return Err(ManagedStoreError::AttestedIdentityDenied);
        }
        Ok(())
    }
}

impl ManagedStore {
    /// Persist each loaded caller contract's generation. Removing and restoring
    /// a caller also advances its generation; old references never regain access.
    pub(crate) fn synchronize_secret_reference_callers_conn(
        conn: &Connection,
        ring: &CredentialKeyRing,
        callers: &[(String, [u8; 32])],
    ) -> Result<BTreeMap<String, i64>, ManagedStoreError> {
        synchronize_callers_conn(conn, ring, callers)
    }

    /// Read-only token validity check shared by source pins and management sinks.
    /// A source pin is not permission to replay the original issuance operation.
    pub(crate) fn check_secret_reference_token_conn(
        conn: &Connection,
        principal: &str,
        token_id: &str,
        class: BrokerTokenClass,
    ) -> Result<(), ManagedStoreError> {
        let token = broker_token_by_id_principal_class(conn, token_id, principal, class)?;
        if token.revoked_at.is_some() {
            return Err(ManagedStoreError::BrokerTokenRevoked);
        }
        if timestamp_is_past(token.expires_at.as_deref()) {
            return Err(ManagedStoreError::BrokerTokenExpired);
        }
        if token.paused_at.is_some() {
            return Err(ManagedStoreError::BrokerTokenPaused);
        }
        let principal = principal_by_id_without_groups(conn, principal)?;
        if principal.status != "active" {
            return Err(ManagedStoreError::PrincipalDisabled);
        }
        if (principal.kind == "service_account"
            && token.token_class != BrokerTokenClass::AgentInvoke)
            || (token.token_class == BrokerTokenClass::Admin
                && (principal.kind != "user" || !principal.role.can_read_admin()))
        {
            return Err(ManagedStoreError::BrokerTokenClassDenied);
        }
        Ok(())
    }

    pub(crate) fn check_secret_reference_callers_without_key_ring_conn(
        conn: &Connection,
    ) -> Result<(), ManagedStoreError> {
        let key: Option<String> = conn
            .query_row(
                "SELECT key_id FROM secret_reference_caller_generations LIMIT 1",
                [],
                |row| row.get(0),
            )
            .optional()
            .map_err(sql_unavailable)?;
        if let Some(key) = key {
            return Err(ManagedStoreError::EncryptionKeyMissing(key));
        }
        Ok(())
    }

    pub(crate) fn check_secret_reference_caller_conn(
        conn: &Connection,
        ring: &CredentialKeyRing,
        caller: &str,
        contract: &[u8; 32],
        generation: i64,
    ) -> Result<(), ManagedStoreError> {
        let row: Option<(String, Vec<u8>, Vec<u8>)> = conn
            .query_row(
                "SELECT key_id,nonce,ciphertext FROM secret_reference_caller_generations
                 WHERE caller=?1 AND generation=?2 AND active=1",
                params![caller, generation],
                |row| Ok((row.get(0)?, row.get(1)?, row.get(2)?)),
            )
            .optional()
            .map_err(sql_unavailable)?;
        let Some((key, nonce, ciphertext)) = row else {
            return Err(ManagedStoreError::AttestedIdentityDenied);
        };
        let stored = secret_references::decrypt_caller_contract(
            ring,
            &key,
            caller,
            generation,
            true,
            &nonce,
            &ciphertext,
        )?;
        if !bool::from(stored.as_slice().ct_eq(contract)) {
            return Err(ManagedStoreError::AttestedIdentityDenied);
        }
        Ok(())
    }
}

fn synchronize_callers_conn(
    conn: &Connection,
    ring: &CredentialKeyRing,
    callers: &[(String, [u8; 32])],
) -> Result<BTreeMap<String, i64>, ManagedStoreError> {
    let previous = {
        let mut stmt = conn
            .prepare("SELECT caller,key_id,nonce,ciphertext,generation,active FROM secret_reference_caller_generations")
            .map_err(sql_unavailable)?;
        let rows = stmt
            .query_map([], |row| {
                Ok((
                    row.get::<_, String>(0)?,
                    row.get::<_, String>(1)?,
                    row.get::<_, Vec<u8>>(2)?,
                    row.get::<_, Vec<u8>>(3)?,
                    row.get::<_, i64>(4)?,
                    row.get::<_, bool>(5)?,
                ))
            })
            .map_err(sql_unavailable)?;
        let mut previous = BTreeMap::new();
        for row in rows {
            let (caller, key, nonce, ciphertext, generation, active) =
                row.map_err(sql_unavailable)?;
            let contract = secret_references::decrypt_caller_contract(
                ring,
                &key,
                &caller,
                generation,
                active,
                &nonce,
                &ciphertext,
            )?;
            previous.insert(caller, (contract, generation, active));
        }
        previous
    };
    let mut generations = BTreeMap::new();
    for (caller, contract) in callers {
        if generations.contains_key(caller) {
            return Err(input_invalid("duplicate trusted caller security contract"));
        }
        let generation = match previous.get(caller) {
            Some((old, generation, true)) if bool::from(old.as_slice().ct_eq(contract)) => {
                generations.insert(caller.clone(), *generation);
                continue;
            }
            Some((_, generation, _)) => next_generation(*generation)?,
            None => 1,
        };
        write_caller_contract(conn, ring, caller, contract, generation, true)?;
        generations.insert(caller.clone(), generation);
    }
    for (caller, (contract, generation, active)) in previous {
        if active && !generations.contains_key(&caller) {
            let contract: &[u8; 32] = contract
                .as_slice()
                .try_into()
                .map_err(|_| ManagedStoreError::CredentialDecryptFailed)?;
            write_caller_contract(
                conn,
                ring,
                &caller,
                contract,
                next_generation(generation)?,
                false,
            )?;
        }
    }
    Ok(generations)
}

fn write_caller_contract(
    conn: &Connection,
    ring: &CredentialKeyRing,
    caller: &str,
    contract: &[u8; 32],
    generation: i64,
    active: bool,
) -> Result<(), ManagedStoreError> {
    let encrypted = secret_references::encrypt_caller_contract(
        ring,
        ring.active_key_id(),
        caller,
        generation,
        active,
        contract,
    )?;
    conn.execute(
        "INSERT INTO secret_reference_caller_generations(caller,key_id,nonce,ciphertext,generation,active)
         VALUES(?1,?2,?3,?4,?5,?6) ON CONFLICT(caller) DO UPDATE SET
         key_id=excluded.key_id,nonce=excluded.nonce,ciphertext=excluded.ciphertext,
         generation=excluded.generation,active=excluded.active",
        params![caller, encrypted.key_id, encrypted.nonce, encrypted.ciphertext, generation, active],
    ).map_err(sql_unavailable)?;
    Ok(())
}

fn next_generation(generation: i64) -> Result<i64, ManagedStoreError> {
    generation
        .checked_add(1)
        .filter(|value| *value > 1)
        .ok_or_else(|| {
            ManagedStoreError::SchemaInvalid(
                "trusted caller generation is invalid or exhausted".into(),
            )
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn store(path: &Path) -> ManagedStore {
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(path.parent().unwrap(), fs::Permissions::from_mode(0o700)).unwrap();
        }
        ManagedStore::open(
            &ManagedStoreConfig {
                kind: "sqlite".into(),
                path: path.display().to_string(),
                require_registered_principal_for_invocation: true,
                auto_migrate: true,
            },
            ManagedStoreOpenMode::Startup,
        )
        .unwrap()
    }

    fn create_user(store: &ManagedStore) {
        store
            .create_principal(PrincipalWriteRequest {
                principal_id: "alice".into(),
                kind: "user".into(),
                role: PrincipalRole::User,
                self_service_enabled: None,
                display_name: None,
                email: None,
                external_subject: None,
                created_by: "admin".into(),
            })
            .unwrap();
    }

    fn current(store: &ManagedStore, pin: &AttestedSecretReferencePin) -> bool {
        pin.check_current_conn(&store.connection.lock().unwrap())
            .is_ok()
    }

    #[test]
    fn username_pin_survives_restart_without_persisting_name_and_rejects_restored_binding() {
        let temp = tempfile::tempdir().unwrap();
        let path = temp.path().join("store.sqlite");
        let initial = store(&path);
        create_user(&initial);
        let binding = initial
            .create_username_binding("alice", "workspace", "operator_987", "admin")
            .unwrap();
        let pin = initial
            .resolve_username_identity("workspace", "operator_987")
            .unwrap()
            .proof
            .secret_reference_pin();
        assert!(pin.valid_shape());
        let encoded = serde_json::to_vec(&pin).unwrap();
        assert!(!String::from_utf8_lossy(&encoded).contains("operator_987"));
        drop(initial);
        let reopened = store(&path);
        let pin: AttestedSecretReferencePin = serde_json::from_slice(&encoded).unwrap();
        assert!(current(&reopened, &pin));
        let disabled = reopened
            .set_username_binding_enabled(
                "alice",
                &binding.binding_id,
                false,
                binding.version,
                "admin",
            )
            .unwrap();
        reopened
            .set_username_binding_enabled(
                "alice",
                &binding.binding_id,
                true,
                disabled.version,
                "admin",
            )
            .unwrap();
        assert!(!current(&reopened, &pin));
        let fresh = reopened
            .resolve_username_identity("workspace", "operator_987")
            .unwrap()
            .proof
            .secret_reference_pin();
        assert!(current(&reopened, &fresh));
        let gate = reopened.identity_access("alice").unwrap();
        let paused = reopened
            .set_identity_access_paused("alice", true, gate.version, "admin")
            .unwrap();
        reopened
            .set_identity_access_paused("alice", false, paused.version, "admin")
            .unwrap();
        assert!(!current(&reopened, &fresh));
    }

    #[test]
    fn fingerprint_pin_excludes_fingerprint_and_rejects_removed_restored_inventory() {
        let temp = tempfile::tempdir().unwrap();
        let store = store(&temp.path().join("store.sqlite"));
        create_user(&store);
        // Synthetic in-memory key material, used only by this deterministic test.
        let ring = CredentialKeyRing {
            active_key: "test".into(),
            keys: Arc::new(BTreeMap::from([("test".into(), [7; 32])])),
        };
        let token = "synthetic-inventory-token-0123456789";
        let fingerprint = format!("sha256:{}", sha256_hex(token.as_bytes()));
        store.set_identity_token("alice", token, &ring).unwrap();
        let pin = store
            .resolve_identity_fingerprint_with_proof(&fingerprint)
            .unwrap()
            .proof
            .secret_reference_pin();
        assert!(pin.valid_shape());
        let encoded = serde_json::to_string(&pin).unwrap();
        assert!(!encoded.contains(token));
        assert!(!encoded.contains(&fingerprint));
        assert!(current(&store, &pin));
        store.remove_identity_token("alice").unwrap();
        store.set_identity_token("alice", token, &ring).unwrap();
        assert!(!current(&store, &pin));
        let fresh = store
            .resolve_identity_fingerprint_with_proof(&fingerprint)
            .unwrap()
            .proof
            .secret_reference_pin();
        assert!(current(&store, &fresh));
        store.set_principal_enabled("alice", false).unwrap();
        store.set_principal_enabled("alice", true).unwrap();
        assert!(!current(&store, &fresh));
    }

    #[test]
    fn token_source_check_requires_live_original_token_without_issuance_grants_or_usage_updates() {
        let temp = tempfile::tempdir().unwrap();
        let store = store(&temp.path().join("store.sqlite"));
        create_user(&store);
        let hasher = BrokerTokenHasher {
            key: Arc::new([3; 32]),
        };
        let issued = store
            .issue_broker_token(
                &hasher,
                BrokerTokenIssueRequest {
                    principal_id: "alice".into(),
                    name: "secret-origin".into(),
                    token_class: BrokerTokenClass::AgentInvoke,
                    scopes: serde_json::json!({"allowedExecutionContexts":["default"]}),
                    expires_at: None,
                    created_by: "admin".into(),
                },
            )
            .unwrap();
        let check = |principal: &str, token: &str, class| {
            ManagedStore::check_secret_reference_token_conn(
                &store.connection.lock().unwrap(),
                principal,
                token,
                class,
            )
        };
        // There are no provider grants: source validity must not require them.
        check(
            "alice",
            &issued.record.token_id,
            BrokerTokenClass::AgentInvoke,
        )
        .unwrap();
        assert!(
            store
                .broker_token(&issued.record.token_id)
                .unwrap()
                .last_used_at
                .is_none()
        );
        assert!(
            check(
                "bob",
                &issued.record.token_id,
                BrokerTokenClass::AgentInvoke
            )
            .is_err()
        );
        assert!(check("alice", &issued.record.token_id, BrokerTokenClass::Admin).is_err());
        store
            .pause_broker_token(&issued.record.token_id, "admin")
            .unwrap();
        assert!(matches!(
            check(
                "alice",
                &issued.record.token_id,
                BrokerTokenClass::AgentInvoke
            ),
            Err(ManagedStoreError::BrokerTokenPaused)
        ));
        store
            .resume_broker_token(&issued.record.token_id, "admin")
            .unwrap();
        check(
            "alice",
            &issued.record.token_id,
            BrokerTokenClass::AgentInvoke,
        )
        .unwrap();
        store.set_principal_enabled("alice", false).unwrap();
        assert!(matches!(
            check(
                "alice",
                &issued.record.token_id,
                BrokerTokenClass::AgentInvoke
            ),
            Err(ManagedStoreError::PrincipalDisabled)
        ));
        store.set_principal_enabled("alice", true).unwrap();
        store
            .revoke_broker_token(&issued.record.token_id, "admin")
            .unwrap();
        assert!(matches!(
            check(
                "alice",
                &issued.record.token_id,
                BrokerTokenClass::AgentInvoke
            ),
            Err(ManagedStoreError::BrokerTokenRevoked)
        ));
    }

    #[test]
    fn caller_generations_survive_restart_and_never_revive_restored_contracts() {
        let temp = tempfile::tempdir().unwrap();
        let path = temp.path().join("ledger.sqlite");
        let ring = CredentialKeyRing {
            active_key: "test".into(),
            keys: Arc::new(BTreeMap::from([("test".into(), [7; 32])])),
        };
        let conn = Connection::open(&path).unwrap();
        conn.execute_batch(include_str!("secret_references.sql"))
            .unwrap();
        let original = vec![("caller".to_string(), [1; 32])];
        assert_eq!(
            synchronize_callers_conn(&conn, &ring, &original).unwrap()["caller"],
            1
        );
        drop(conn);
        let conn = Connection::open(&path).unwrap();
        assert_eq!(
            synchronize_callers_conn(&conn, &ring, &original).unwrap()["caller"],
            1
        );
        let changed = vec![("caller".to_string(), [2; 32])];
        assert_eq!(
            synchronize_callers_conn(&conn, &ring, &changed).unwrap()["caller"],
            2
        );
        assert_eq!(
            synchronize_callers_conn(&conn, &ring, &original).unwrap()["caller"],
            3
        );
        assert!(
            ManagedStore::check_secret_reference_caller_conn(&conn, &ring, "caller", &[1; 32], 1)
                .is_err()
        );
        ManagedStore::check_secret_reference_caller_conn(&conn, &ring, "caller", &[1; 32], 3)
            .unwrap();
        synchronize_callers_conn(&conn, &ring, &[]).unwrap();
        synchronize_callers_conn(&conn, &ring, &[]).unwrap();
        assert_eq!(
            synchronize_callers_conn(&conn, &ring, &original).unwrap()["caller"],
            5
        );
        assert!(
            ManagedStore::check_secret_reference_caller_conn(&conn, &ring, "caller", &[1; 32], 3)
                .is_err()
        );
    }
}
