import { vi } from "vitest";
vi.mock("../src/app/session", () => ({ useSession: () => ({ session: { authenticated: true, role: "admin", selfServiceEnabled: true, principal: "admin" } }) }));
import { describe, expect, test } from "vitest";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { ResourceAttributeField } from "../src/features/catalog/resource-attributes";
import { grantResourceChoices } from "../src/lib/grant-resources";
import { indexResourceTypes, namespaceCoverage, resourceTypeLabel, selectorPlaceholder, supportsResourceExclusions } from "../src/lib/resource-types";
import { resourceLabel, selectorLabel } from "../src/lib/resource-labels";
import type { PolicyServiceCatalog, ResourceDefinition, ResourceRecord, ResourceTypeMetadata } from "../src/types";
import conformance from "./conformance.fixture.json";
import { RESOURCE_TYPES } from "./resource-types.fixture";

// The broker's view of its test-only conformance backend, generated by the
// broker test `conformance_portal_fixture_matches_the_broker`. The portal has
// no knowledge of this backend: everything below comes from the fixture.
const resourceType = conformance.resourceType as ResourceTypeMetadata;
const endpointType = conformance.endpointType as ResourceTypeMetadata;
const service = conformance.service as PolicyServiceCatalog;
const types = indexResourceTypes([...RESOURCE_TYPES, resourceType]);

describe("a backend the portal was not written for", () => {
  test("labels its resource type and selectors from broker metadata", () => {
    expect(resourceTypeLabel(types, "conformance_item")).toBe("Conformance item");
    expect(selectorLabel(types, "conformance_item", { kind: "exact", value: "shelf-one/item-one" })).toBe("shelf-one/item-one");
    expect(selectorLabel(types, "conformance_item", { kind: "namespace", value: "shelf-one" })).toBe("Items under shelf-one");
    expect(selectorLabel(types, "conformance_item", { kind: "all" })).toBe("All Conformance items");
    expect(namespaceCoverage(types, "conformance_item")?.label).toBe("Items on a shelf");
    expect(selectorPlaceholder(types, "conformance_item", "exact")).toBe("shelf-one/item-one");
    expect(selectorPlaceholder(types, "conformance_item", "namespace")).toBe("shelf-one");
    const shelf: ResourceRecord = {
      id: "shelf", resourceType: "conformance_item", selector: { kind: "namespace", value: "shelf-one" },
      allowedExecutionContexts: ["internal"], enabled: true, version: 1
    };
    expect(resourceLabel(types, shelf)).toBe("Items under shelf-one");
  });

  test("honors exclusion capabilities supplied by an unfamiliar backend", () => {
    const registered = indexResourceTypes([resourceType, endpointType]);
    expect(resourceType.supportsExclusions).toBe(true);
    expect(endpointType.supportsExclusions).toBe(false);
    expect(supportsResourceExclusions(registered, resourceType.id)).toBe(true);
    expect(supportsResourceExclusions(registered, endpointType.id)).toBe(false);
  });

  test("offers only its own resources when granting its actions", () => {
    const resource = (id: string, resourceType: string): ResourceDefinition => ({
      id, resourceType, displayName: id, selector: { kind: "exact", value: id }, enabled: true, allowedExecutionContexts: ["internal"]
    });
    const catalog = {
      resources: [resource("item", "conformance_item"), resource("repo", "git_repository")],
      resourceGroups: [{ id: "mixed", name: "mixed", includedResourceIds: ["item", "repo"], excludedResourceIds: [], version: 1 }]
    };
    const choices = grantResourceChoices(catalog, service, { resourceIds: ["item"], resourceGroupIds: [] }, ["internal"]);
    expect(choices.resources.map(({ id }) => id)).toEqual(["item"]);
    expect(choices.groups[0].included).toEqual(["item"]);
    expect(choices.hasMismatch).toBe(false);
    expect(service.actions.map(({ action }) => action)).toEqual(["item.view", "item.download", "item.upload", "item.list"]);
    expect(service.actions.map(({ readOnly }) => readOnly)).toEqual([true, true, false, true]);
  });

  test("recognizes explicit live enumeration from an unfamiliar backend", () => {
    expect(service.actions.filter(({ listingOf }) => listingOf).map(({ action, listingOf }) => ({ action, listingOf }))).toEqual([
      { action: "item.list", listingOf: "conformance_item" }
    ]);
  });

  test("builds private attribute fields from its type metadata", () => {
    const [field] = endpointType.attributes ?? [];
    expect(field).toMatchObject({ name: "signingKey", label: "Signing key", required: true });
    const render = (configured: boolean) => renderToStaticMarkup(createElement(ResourceAttributeField, {
      field, configured, value: "", busy: false, onChange: () => undefined, onReveal: async () => ""
    }));
    const unconfigured = render(false);
    expect(unconfigured).toContain("Signing key");
    expect(unconfigured).toContain(field.description);
    expect(unconfigured).toContain("required");
    expect(unconfigured).toContain('type="password"');
    const configured = render(true);
    expect(configured).toContain("Replacement Signing key");
    expect(configured).toContain("(optional)");
    expect(configured).toContain("Leave the replacement blank to keep the current value.");
    expect(configured).toContain("Reveal Signing key");
    expect(configured).not.toContain("required");
  });
});
